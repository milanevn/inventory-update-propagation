package edu.inventory.node.core;

import com.fasterxml.jackson.annotation.JsonIgnore;
import edu.inventory.domain.EventType;

/**
 * Type-specific content of an event, stored as JSON in {@code operation_log.payload}
 * (schema version 1, format in docs/thiet-ke.md section 3). The constructors reject content that
 * could never have been committed, so a corrupt log or a malformed replicated event fails early.
 */
public sealed interface EventPayload {

    @JsonIgnore
    EventType type();

    record ProductCreated(String productCode, String productName, String unit) implements EventPayload {
        public ProductCreated {
            requireText(productCode, "productCode");
            requireText(productName, "productName");
            requireText(unit, "unit");
        }

        @Override public EventType type() {
            return EventType.CREATE_PRODUCT;
        }
    }

    /** @param voucherNo generated by the primary: {@code IN-<epoch>-<seq>} */
    record StockIn(String productCode, long quantity, String voucherNo) implements EventPayload {
        public StockIn {
            requireText(productCode, "productCode");
            requirePositive(quantity);
            requireText(voucherNo, "voucherNo");
        }

        @Override public EventType type() {
            return EventType.STOCK_IN;
        }
    }

    /** @param voucherNo generated by the primary: {@code OUT-<epoch>-<seq>} */
    record StockOut(String productCode, long quantity, String voucherNo) implements EventPayload {
        public StockOut {
            requireText(productCode, "productCode");
            requirePositive(quantity);
            requireText(voucherNo, "voucherNo");
        }

        @Override public EventType type() {
            return EventType.STOCK_OUT;
        }
    }

    record PolicyChanged(PolicyParameter parameter, int newValue, long configurationVersion) implements EventPayload {
        public PolicyChanged {
            if (parameter == null || !parameter.accepts(newValue))
                throw new IllegalArgumentException("Invalid policy value " + parameter + "=" + newValue);
            if (configurationVersion < 2)
                throw new IllegalArgumentException("configurationVersion must be >= 2: " + configurationVersion);
        }

        @Override public EventType type() {
            return EventType.POLICY_CHANGE;
        }
    }

    record EpochStarted(String primaryNodeId, String s4SourceNodeId) implements EventPayload {
        public EpochStarted {
            requireText(primaryNodeId, "primaryNodeId");
            requireText(s4SourceNodeId, "s4SourceNodeId");
        }

        @Override public EventType type() {
            return EventType.EPOCH_START;
        }
    }

    private static void requireText(String value, String name) {
        if (value == null || value.isBlank()) throw new IllegalArgumentException(name + " is required");
    }

    private static void requirePositive(long quantity) {
        if (quantity <= 0) throw new IllegalArgumentException("quantity must be > 0: " + quantity);
    }
}
